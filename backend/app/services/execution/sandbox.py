"""Isolated Python execution sandbox.

Security model (MVP, agreed in Phase 1):

* **Process isolation** — student code runs in a *separate* Python process,
  never via ``exec`` inside the FastAPI worker.
* **Timeout** — the process is killed if it exceeds a wall-clock limit.
* **Output cap** — stdout/stderr are truncated to a byte limit.
* **Filesystem** — the process runs in a throwaway temp directory that is
  deleted afterwards; the harness also blocks ``open`` for writing.
* **Network** — the harness monkeypatches ``socket`` to deny connections.
* **Environment** — the subprocess gets a stripped environment (no inherited
  secrets), isolated mode (``-I``), and no site packages pollution.
* **Memory/CPU** — on POSIX, ``resource`` limits are applied in a preexec
  hook. On Windows ``resource`` is unavailable, so we rely on the timeout and
  output cap (documented limitation; the clean upgrade path is a Docker-based
  runner that this module can be swapped for without touching callers).

The module exposes a single ``run_in_sandbox`` function returning a
``SandboxOutcome``. The harness itself is generated by ``runner.py`` and passed
in as ``script``; this module only cares about *how* to run it safely.
"""

from __future__ import annotations

import logging
import os
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass

logger = logging.getLogger("debugly.sandbox")

# ---- Limits (conservative defaults for the MVP) ----
DEFAULT_TIMEOUT_SECONDS = 6.0
MAX_OUTPUT_BYTES = 64 * 1024          # 64 KB per stream
MAX_MEMORY_BYTES = 256 * 1024 * 1024  # 256 MB (POSIX via rlimit; Windows via Job Object)
MAX_SCRIPT_BYTES = 256 * 1024         # hard cap on the full harness+code we will run

IS_WINDOWS = os.name == "nt"


class SandboxSetupError(RuntimeError):
    """Raised when a script is rejected before execution (e.g. too large)."""


@dataclass
class SandboxOutcome:
    """Raw result of running a script in the sandbox."""

    stdout: str
    stderr: str
    exit_code: int | None
    timed_out: bool
    stdout_truncated: bool
    stderr_truncated: bool
    duration_ms: int


def _truncate(data: bytes, limit: int) -> tuple[str, bool]:
    """Decode and truncate a stream to ``limit`` bytes."""
    truncated = len(data) > limit
    clipped = data[:limit]
    text = clipped.decode("utf-8", errors="replace")
    # Normalize Windows CRLF / stray CR so the terminal panel renders cleanly.
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if truncated:
        text += "\n...[output truncated]"
    return text, truncated


def _posix_preexec() -> None:  # pragma: no cover - POSIX only
    """Apply resource limits in the child before exec (POSIX only)."""
    import resource  # imported lazily; absent on Windows

    # Address-space (memory) cap.
    resource.setrlimit(resource.RLIMIT_AS, (MAX_MEMORY_BYTES, MAX_MEMORY_BYTES))
    # CPU-time cap as a backstop to the wall-clock timeout.
    cpu = int(DEFAULT_TIMEOUT_SECONDS) + 1
    resource.setrlimit(resource.RLIMIT_CPU, (cpu, cpu))
    # No core dumps.
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    # New session so we can kill the whole process group on timeout.
    os.setsid()


def _minimal_env() -> dict[str, str]:
    """Build a stripped environment for the child process."""
    env: dict[str, str] = {
        "PATH": os.environ.get("PATH", ""),
        "PYTHONIOENCODING": "utf-8",
        "PYTHONDONTWRITEBYTECODE": "1",
        # Deny implicit network/proxy config.
        "no_proxy": "*",
    }
    # On Windows a few vars are needed for the interpreter to start.
    if IS_WINDOWS:
        for key in ("SYSTEMROOT", "TEMP", "TMP", "PATHEXT"):
            if key in os.environ:
                env[key] = os.environ[key]
    return env


def _apply_windows_memory_cap(pid: int) -> object | None:  # pragma: no cover - Windows only
    """Assign the child process to a Job Object with a committed-memory cap.

    Returns the job handle (keep it alive for the process lifetime) or None if
    the OS/APIs are unavailable. Best-effort: a failure here degrades to the
    timeout + output caps, it never blocks execution.
    """
    if not IS_WINDOWS:
        return None
    try:
        import ctypes
        from ctypes import wintypes

        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)

        JOB_OBJECT_LIMIT_PROCESS_MEMORY = 0x00000100
        JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE = 0x00002000
        JobObjectExtendedLimitInformation = 9
        PROCESS_SET_QUOTA = 0x0100
        PROCESS_TERMINATE = 0x0001

        class IO_COUNTERS(ctypes.Structure):
            _fields_ = [(n, ctypes.c_ulonglong) for n in (
                "ReadOperationCount", "WriteOperationCount", "OtherOperationCount",
                "ReadTransferCount", "WriteTransferCount", "OtherTransferCount")]

        class JOBOBJECT_BASIC_LIMIT_INFORMATION(ctypes.Structure):
            _fields_ = [
                ("PerProcessUserTimeLimit", wintypes.LARGE_INTEGER),
                ("PerJobUserTimeLimit", wintypes.LARGE_INTEGER),
                ("LimitFlags", wintypes.DWORD),
                ("MinimumWorkingSetSize", ctypes.c_size_t),
                ("MaximumWorkingSetSize", ctypes.c_size_t),
                ("ActiveProcessLimit", wintypes.DWORD),
                ("Affinity", ctypes.POINTER(wintypes.ULONG)),
                ("PriorityClass", wintypes.DWORD),
                ("SchedulingClass", wintypes.DWORD),
            ]

        class JOBOBJECT_EXTENDED_LIMIT_INFORMATION(ctypes.Structure):
            _fields_ = [
                ("BasicLimitInformation", JOBOBJECT_BASIC_LIMIT_INFORMATION),
                ("IoInfo", IO_COUNTERS),
                ("ProcessMemoryLimit", ctypes.c_size_t),
                ("JobMemoryLimit", ctypes.c_size_t),
                ("PeakProcessMemoryUsed", ctypes.c_size_t),
                ("PeakJobMemoryUsed", ctypes.c_size_t),
            ]

        job = kernel32.CreateJobObjectW(None, None)
        if not job:
            return None

        info = JOBOBJECT_EXTENDED_LIMIT_INFORMATION()
        info.BasicLimitInformation.LimitFlags = (
            JOB_OBJECT_LIMIT_PROCESS_MEMORY | JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE
        )
        info.ProcessMemoryLimit = MAX_MEMORY_BYTES
        if not kernel32.SetInformationJobObject(
            job, JobObjectExtendedLimitInformation, ctypes.byref(info), ctypes.sizeof(info)
        ):
            kernel32.CloseHandle(job)
            return None

        hproc = kernel32.OpenProcess(PROCESS_SET_QUOTA | PROCESS_TERMINATE, False, pid)
        if not hproc:
            kernel32.CloseHandle(job)
            return None
        ok = kernel32.AssignProcessToJobObject(job, hproc)
        kernel32.CloseHandle(hproc)
        if not ok:
            kernel32.CloseHandle(job)
            return None
        return job  # keep alive; closing it kills the job (KILL_ON_JOB_CLOSE)
    except Exception:
        logger.debug("Windows Job Object memory cap unavailable", exc_info=True)
        return None


def run_in_sandbox(
    script: str,
    *,
    timeout: float = DEFAULT_TIMEOUT_SECONDS,
) -> SandboxOutcome:
    """Run ``script`` as an isolated subprocess and capture the result.

    ``script`` is the full program text to execute (student code + harness).
    Returns a :class:`SandboxOutcome`; never raises for ordinary student
    errors (those surface via exit code / stderr).

    Raises :class:`SandboxSetupError` if the script exceeds the hard size cap.
    """
    if len(script.encode("utf-8", errors="ignore")) > MAX_SCRIPT_BYTES:
        raise SandboxSetupError("Program is too large to execute safely.")

    start = time.perf_counter()
    _job_handle = None  # Windows Job Object (kept alive during execution)

    with tempfile.TemporaryDirectory(prefix="debugly_sbx_") as workdir:
        script_path = os.path.join(workdir, "main.py")
        with open(script_path, "w", encoding="utf-8") as fh:
            fh.write(script)

        # ``-I`` = isolated mode: ignores env vars like PYTHONPATH and the
        # user site dir, and does not prepend cwd to sys.path.
        cmd = [sys.executable, "-I", "-B", script_path]

        popen_kwargs: dict = {
            "stdout": subprocess.PIPE,
            "stderr": subprocess.PIPE,
            "cwd": workdir,
            "env": _minimal_env(),
        }

        if IS_WINDOWS:
            # Allow killing the whole tree on timeout.
            popen_kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP
        else:  # pragma: no cover - POSIX only
            popen_kwargs["preexec_fn"] = _posix_preexec

        timed_out = False
        try:
            proc = subprocess.Popen(cmd, **popen_kwargs)
        except Exception:
            logger.exception("Failed to spawn sandbox subprocess")
            duration_ms = int((time.perf_counter() - start) * 1000)
            return SandboxOutcome(
                stdout="",
                stderr="Internal error: could not start execution sandbox.",
                exit_code=None,
                timed_out=False,
                stdout_truncated=False,
                stderr_truncated=False,
                duration_ms=duration_ms,
            )

        # On Windows, cap committed memory via a Job Object (best-effort).
        if IS_WINDOWS:
            _job_handle = _apply_windows_memory_cap(proc.pid)

        try:
            raw_out, raw_err = proc.communicate(timeout=timeout)
        except subprocess.TimeoutExpired:
            timed_out = True
            _kill(proc)
            raw_out, raw_err = proc.communicate()
        finally:
            if _job_handle is not None:  # pragma: no cover - Windows only
                try:
                    import ctypes

                    ctypes.WinDLL("kernel32").CloseHandle(_job_handle)
                except Exception:
                    pass

        exit_code = proc.returncode

    stdout, out_trunc = _truncate(raw_out or b"", MAX_OUTPUT_BYTES)
    stderr, err_trunc = _truncate(raw_err or b"", MAX_OUTPUT_BYTES)
    duration_ms = int((time.perf_counter() - start) * 1000)

    return SandboxOutcome(
        stdout=stdout,
        stderr=stderr,
        exit_code=exit_code,
        timed_out=timed_out,
        stdout_truncated=out_trunc,
        stderr_truncated=err_trunc,
        duration_ms=duration_ms,
    )


def _kill(proc: subprocess.Popen) -> None:
    """Terminate a (possibly group-leading) process, best-effort."""
    try:
        if IS_WINDOWS:
            # Kill the whole tree.
            subprocess.run(
                ["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                capture_output=True,
                check=False,
            )
        else:  # pragma: no cover - POSIX only
            import signal

            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
    except Exception:
        logger.warning("Failed to kill sandbox process %s", proc.pid, exc_info=True)
        try:
            proc.kill()
        except Exception:
            pass
